import re

phrases = [
    "Кто настраивал связку мойсклад и каспи?",
    "Не получается поймать коэффициент на Коледино, постоянно x20",
    "Я знаю, удалось создать только на Чашниково, остальное все что нужно недоступно..."
]

p1 = r"(?:кто|как|помогите|нужно|нужна|нужен)?\s*.*(?:синхронизаци|связк|интеграци)\s+.*(?:1с|1c|мойсклад|wb|ozon|вб|озон|каспи|kaspi)"
p2 = r"(?:не могу|не удается|не получается)\s+.*(?:поймать|забронировать|создать|открыть|поставить)\s+.*(?:слот|поставк|приемк|склад|коэффициент)"
p3 = r"(?:коледино|электросталь|чашниково|тула|подольск).*?(?:недоступн|забит|закрыт|нет мест)"

for phr in phrases:
    print("PHRASE:", phr)
    print("  p1:", bool(re.search(p1, phr.lower(), re.DOTALL)))
    print("  p2:", bool(re.search(p2, phr.lower(), re.DOTALL)))
    print("  p3:", bool(re.search(p3, phr.lower(), re.DOTALL)))
