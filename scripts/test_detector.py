PAIN_KASPI_PATTERNS = [
    r"(?:демпинг|автопрайсер|автоснижение|снизить цену на 10|байбокс|buybox|кнопк[ау]\s+купить)",
    r"(?:упали|просели|мало)\s+.*(?:заказы|продажи|показы)\s+.*(?:каспи|kaspi|вдвое|в двое)",
    r"рекламн(?:ый|ого)\s+бот[а]?"
]

STOP_WORDS = ["карго", "перевозки из китая", "выкуплю", "ребята 16+", "даю по 500р", "вернуть страховку"]

def check_msg(text):
    tl = text.lower()
    if any(s in tl for s in STOP_WORDS):
        return None, None
    for p in TIER1_PATTERNS:
        m = re.search(p, tl)
        if m: return "DIRECT_ORDER", m.group(0)
    for p in PAIN_PRICES_PATTERNS:
        m = re.search(p, tl)
        if m: return "SELLER_PAIN_PRICES", m.group(0)
    for p in PAIN_SLOTS_PATTERNS:
        m = re.search(p, tl)
        if m: return "SELLER_PAIN_SLOTS", m.group(0)
    for p in PAIN_STOCK_PATTERNS:
        m = re.search(p, tl)
        if m: return "SELLER_PAIN_STOCK", m.group(0)
    for p in PAIN_KASPI_PATTERNS:
        m = re.search(p, tl)
        if m: return "SELLER_PAIN_KASPI", m.group(0)
    return None, None

for phr in TEST_PHRASES:
    cat, match = check_msg(phr)
    print(f"[{cat}] match: '{match}' | Phrase: {phr[:45]}...")
